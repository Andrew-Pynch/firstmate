# function that created it has returned, so it is held at file scope rather than
# in a local.
RECORD_TMP=""

usage() {
  printf '%s\n' \
    'usage: fm-farm-patch.sh [--store <dir>] [--base <rev>] list|check|record|replay|where [<target>...]' \
    '  list              print the ordered, named patch set and its revision' \
    '  check <target>    compare a checkout against the content the set produces' \
    '  record <target>   write one patch into the set from a commit or a diff' \
    '  replay <target>   rebuild the patched lineage and point <target> at it' \
    '  where [<target>|<host>:<root>]...' \
    '                    name each code root and whether it carries this set' \
    '  --fleet <home>    where: the home as primary plus every second mate root' \
    '  --store <dir>     the patch store (default: <repo-root>/farm-patches)' \
    '  --base <rev>      the base the series is replayed and verified on' \
    '                    (default: the base the manifest records)' \
    'record only:' \
    '  --slug <slug>     the patch name, and its file name with its id' \
    '  --id <NNNN>       replace this existing patch instead of adding one' \
    '  --diff <file|->   the unified diff to record, or - to read stdin' \
    '  --commit <rev>    the commit whose diff to record, read from --repo' \
    '  --repo <dir>      the repository --commit is read from (default: <target>)' \
    '  --from <rev>      the revision the diff starts at (default: <commit>^)' \
    '  --origin <text>   where the patch comes from, recorded in the manifest' \
    '  --purpose <text>  why the patch exists, recorded in the manifest' \
    '  --subject <text>  its commit subject when the series is replayed' \
    '  --note <text>     the note stored with the new series base' \
    'A conflict on replay stops there: the target is never touched, and the' \
    'scratch worktree it names is kept as it stopped. Commit the resolution' \
    'there and regenerate the patch with record before removing it.'
}

die() { printf 'error: %s\n' "$1" >&2; exit 1; }

parse_args() {
  while [ $# -gt 0 ]; do
    case "$1" in
      --store) [ $# -ge 2 ] || die '--store needs a directory'; STORE=$2; shift 2 ;;
      --base) [ $# -ge 2 ] || die '--base needs a revision'; BASE_REV=$2; shift 2 ;;
      --slug) [ $# -ge 2 ] || die '--slug needs a name'; SLUG=$2; shift 2 ;;
      --id) [ $# -ge 2 ] || die '--id needs a patch id'; RECORD_ID=$2; shift 2 ;;
      --repo) [ $# -ge 2 ] || die '--repo needs a directory'; RECORD_REPO=$2; shift 2 ;;
      --from) [ $# -ge 2 ] || die '--from needs a revision'; RECORD_FROM=$2; shift 2 ;;
      --commit) [ $# -ge 2 ] || die '--commit needs a revision'; RECORD_COMMIT=$2; shift 2 ;;
      --diff) [ $# -ge 2 ] || die '--diff needs a file or -'; RECORD_DIFF=$2; shift 2 ;;
      --origin) [ $# -ge 2 ] || die '--origin needs text'; RECORD_ORIGIN=$2; shift 2 ;;
      --purpose) [ $# -ge 2 ] || die '--purpose needs text'; RECORD_PURPOSE=$2; shift 2 ;;
      --subject) [ $# -ge 2 ] || die '--subject needs text'; RECORD_SUBJECT=$2; shift 2 ;;
      --note) [ $# -ge 2 ] || die '--note needs text'; RECORD_NOTE=$2; shift 2 ;;
      --fleet) [ $# -ge 2 ] || die '--fleet needs a firstmate home'; WHERE_FLEET=$2; shift 2 ;;
      -h|--help) usage; exit 0 ;;
      -*) die "unknown option: $1" ;;
      *)
        if [ -z "$VERB" ]; then VERB=$1
        elif [ "$VERB" = where ]; then WHERE_TARGETS+=("$1")
        elif [ -z "$TARGET" ]; then TARGET=$1
        else die "unexpected argument: $1"; fi
        shift ;;
    esac
  done
  [ -n "$VERB" ] || { usage >&2; exit 1; }
}

manifest_file() {
  [ -f "$STORE/manifest" ] || die "no manifest in store $STORE"
  printf '%s/manifest\n' "$STORE"
}

# Records are tab-separated; blank lines and # comments are not records. Printing
# them unchanged keeps the parse in one place: every consumer filters on $1.
manifest_records() {  # <manifest>
  awk -F'\t' 'NF > 0 && $1 !~ /^#/' "$1"
}

series_base() {  # <manifest> -> prints the recorded verified base, or nothing
  manifest_records "$1" | awk -F'\t' '$1 == "series" { print $2; exit }'
}

patch_records() {  # <manifest>
  manifest_records "$1" | awk -F'\t' '$1 == "patch"'
}

patch_field() {  # <manifest> <index> <column>
  patch_records "$1" | awk -F'\t' -v n="$2" -v c="$3" 'NR == n { print $c; exit }'
}

patch_count() {  # <manifest>
  patch_records "$1" | awk 'END { print NR + 0 }'
}

list_verb() {
  local manifest base count i id slug file
  manifest=$STORE/manifest
  manifest_file >/dev/null
  base=$(series_base "$manifest")
  count=$(patch_count "$manifest")
  printf 'store\t%s\n' "$STORE"
  printf 'base\t%s\n' "${base:-unknown}"
  printf 'patches\t%s\n' "$count"
  printf 'revision\t%s\n' "$(store_revision "$manifest")"
  if [ -f "$STORE/expected.tsv" ]; then
    printf 'content\t%s\n' "$(expected_content)"
  else
    printf 'content\tunknown\n'
  fi
  i=0
  while [ "$i" -lt "$count" ]; do
    i=$((i + 1))
    id=$(patch_field "$manifest" "$i" 2)
    slug=$(patch_field "$manifest" "$i" 3)
    file=$(patch_field "$manifest" "$i" 4)
    printf '%s\t%s\t%s\n' "$id" "$slug" "$file"
  done
}

# The set's own identity: the verified base, then every patch's id, slug and
# exact bytes in application order. Two stores that print the same revision
# replay the same series; a comment edit in the manifest does not change it.
store_revision() {  # <manifest>
  local manifest=$1 count i id slug file
  count=$(patch_count "$manifest")
  {
    printf 'series\t%s\n' "$(series_base "$manifest")"
    i=0
    while [ "$i" -lt "$count" ]; do
      i=$((i + 1))
      id=$(patch_field "$manifest" "$i" 2)
      slug=$(patch_field "$manifest" "$i" 3)
      file=$(patch_field "$manifest" "$i" 4)
      printf 'patch\t%s\t%s\n' "$id" "$slug"
      cat "$STORE/$file" 2>/dev/null || printf 'missing\t%s\n' "$file"
    done
  } | sha256_stream
}

# The digest `check` prints as its `set` line for a checkout that carries the
# set exactly, computed from expected.tsv alone.
expected_content() {
  awk 'NF' "$STORE/expected.tsv" | LC_ALL=C sort | sha256_stream
}

# One file's actual identity in a checkout, as git would store it: the mode, and
# the blob hash with the path's own clean filter applied, so a checkout that
# normalizes line endings still matches the stored blob.
file_identity() {  # <target> <path>
  local target=$1 path=$2
  [ -e "$target/$path" ] || { printf '000000\t-\t%s\n' "$path"; return 0; }
  local mode hash
  if [ -x "$target/$path" ]; then mode=100755; else mode=100644; fi
  hash=$(git -C "$target" hash-object --path="$path" -- "$path" 2>/dev/null) || hash=
  [ -n "$hash" ] || { printf 'unreadable\t\t%s\n' "$path"; return 0; }
  printf '%s\t%s\t%s\n' "$mode" "$hash" "$path"
}

# SHA-256 of stdin, truncated to the 16 hex characters the `set` line reports.
# macOS ships shasum and not sha256sum, and two hosts this must run on are macOS,
# so this follows the house order rather than assuming a GNU coreutils hash.
# check_verb proves one of the two exists first, because a failure inside a
# command substitution would only end that subshell.
sha256_stream() {
  if command -v shasum >/dev/null 2>&1; then
    shasum -a 256 | cut -c1-16
  else
    sha256sum | cut -c1-16
  fi
}

check_verb() {
  local target=$1 expected line mode hash path actual amode ahash verdict
  local total=0 matched=0 differing=0
  local set_lines=""
  [ -n "$target" ] || die 'check needs a target checkout'
  [ -d "$target" ] || die "target is not a directory: $target"
  git -C "$target" rev-parse --is-inside-work-tree >/dev/null 2>&1 \
    || die "target is not a git checkout: $target"
  expected="$STORE/expected.tsv"
  [ -f "$expected" ] || die "the store has no expected.tsv; run replay to record what the set produces"
  command -v shasum >/dev/null 2>&1 || command -v sha256sum >/dev/null 2>&1 \
    || die 'neither shasum nor sha256sum is available to identify the checked content'
  while IFS= read -r line; do
    [ -n "$line" ] || continue
    mode=$(printf '%s' "$line" | cut -f1)
    hash=$(printf '%s' "$line" | cut -f2)
    path=$(printf '%s' "$line" | cut -f3-)
    actual=$(file_identity "$target" "$path")
    amode=$(printf '%s' "$actual" | cut -f1)
    ahash=$(printf '%s' "$actual" | cut -f2)
    total=$((total + 1))
    if [ "$amode" = "$mode" ] && [ "$ahash" = "$hash" ]; then
      matched=$((matched + 1))
      verdict=match
    else
      differing=$((differing + 1))
      case "$amode" in
        unreadable) verdict=unreadable ;;
        000000) verdict=absent ;;
        *) verdict=differs ;;
      esac
    fi
    set_lines="${set_lines}${actual}
"
    printf '%s\t%s\t%s\t%s\n' "$verdict" "$path" "$hash" "$ahash"
  done < "$expected"
  printf 'summary\t%s files, %s matched, %s differing\n' "$total" "$matched" "$differing"
  printf 'set\t%s\n' "$(printf '%s' "$set_lines" | LC_ALL=C sort | sha256_stream)"
  [ "$differing" -eq 0 ]
}

# The half of `where` that reads a root. It is also what runs on a remote host:
# where_remote ships this function and file_identity by source, so the host
# needs git and nothing from this repository. <mode> is `content` (the root's
# HEAD, uncommitted path count, and the identity of every path on stdin) or
# `entry` (the checkout fm-remote-entrypoint.sh resolves to on this host's
# non-interactive PATH). Always read-only, and it reports a missing root rather
# than failing, so one bad row never hides the others.
where_probe() {  # <mode> <root>
  local mode=$1 root=$2 resolved entry real path ref
  PATH="/opt/homebrew/bin:/usr/local/bin:$HOME/.local/bin:$PATH"
  GIT_OPTIONAL_LOCKS=0
  export PATH GIT_OPTIONAL_LOCKS
  if [ "$mode" = entry ]; then
    real=
    entry=$(command -v fm-remote-entrypoint.sh 2>/dev/null) || entry=
    if [ -n "$entry" ]; then
      real=$(realpath "$entry" 2>/dev/null) \
        || real=$(python3 -c 'import os, sys; print(os.path.realpath(sys.argv[1]))' "$entry" 2>/dev/null) \
        || real=
    fi
    if [ -n "$real" ] && resolved=$(cd "$(dirname "$real")/.." 2>/dev/null && pwd -P); then
      printf 'entry\t%s\n' "$resolved"
    else
      printf 'entry\t-\n'
    fi
    return 0
  fi
  if ! resolved=$(cd "$root" 2>/dev/null && pwd -P) \
    || ! git -C "$resolved" rev-parse --is-inside-work-tree >/dev/null 2>&1; then
    printf 'missing\t%s\n' "$root"
    return 0
  fi
  ref=$(git -C "$resolved" symbolic-ref --quiet --short HEAD 2>/dev/null) || ref=detached
  printf 'root\t%s\n' "$resolved"
  printf 'head\t%s\t%s\n' "$(git -C "$resolved" rev-parse HEAD)" "$ref"
  printf 'dirty\t%s\n' "$(git -C "$resolved" status --porcelain | awk 'END { print NR + 0 }')"
  while IFS= read -r path; do
    [ -n "$path" ] || continue
    printf 'id\t%s\n' "$(file_identity "$resolved" "$path")"
  done
}

# Run where_probe on <host> over non-interactive ssh. The probe travels as
# base64 so no login shell (zsh on some hosts) re-parses it, and the paths to
# identify travel on stdin. bash runs with --norc and no BASH_ENV because bash
# started under sshd reads ~/.bashrc even for -c, and a .bashrc that starts
# another shell would then execute those paths as commands.
where_remote() {  # <host> <mode> <root>
  local host=$1 mode=$2 root=$3 src b64
  case "$host$root" in *"'"*) printf 'missing\t%s\n' "$root"; return 0 ;; esac
  src="$(declare -f file_identity where_probe); where_probe \"\$@\""
  b64=$(printf '%s' "$src" | base64 | tr -d '\n')
  # shellcheck disable=SC2029 # the probe is deliberately expanded here and decoded there.
  "${FM_FARM_PATCH_SSH:-ssh}" -o BatchMode=yes -o ConnectTimeout=10 "$host" \
    "s=\$(printf %s '$b64' | base64 -d 2>/dev/null) || s=\$(printf %s '$b64' | base64 -D); exec env BASH_ENV= bash --norc --noprofile -c \"\$s\" fm-farm-where '$mode' '$root'"
}

WHERE_OK=1
WHERE_LAST_ROOT=""
WHERE_HOST=""

# One `where` row: label, host, resolved root, HEAD, branch or detached, the
# uncommitted path count, the content digest (`check`'s `set` line), and the
# verdict against this store.
where_row() {  # <label> <host, empty for this host> <root>
  local label=$1 host=$2 root=$3 expected=$STORE/expected.tsv out rc=0
  local shown resolved head ref dirty ids content differing total read_count verdict
  WHERE_LAST_ROOT=$root
  shown=${host:-$WHERE_HOST}
  if [ -n "$host" ]; then
    out=$(cut -f3- "$expected" | where_remote "$host" content "$root" 2>/dev/null) || rc=$?
  else
    out=$(cut -f3- "$expected" | (where_probe content "$root")) || rc=$?
  fi
  if [ "$rc" -ne 0 ] || [ -z "$out" ]; then
    printf 'where\t%s\t%s\t%s\tunreachable\n' "$label" "$shown" "$root"
    WHERE_OK=0
    return 0
  fi
  if printf '%s\n' "$out" | grep -q '^missing	'; then
    printf 'where\t%s\t%s\t%s\tmissing\n' "$label" "$shown" "$root"
    WHERE_OK=0
    return 0
  fi
  resolved=$(printf '%s\n' "$out" | sed -n 's/^root	//p')
  head=$(printf '%s\n' "$out" | sed -n 's/^head	//p' | cut -f1)
  ref=$(printf '%s\n' "$out" | sed -n 's/^head	//p' | cut -f2)
  dirty=$(printf '%s\n' "$out" | sed -n 's/^dirty	//p')
  ids=$(printf '%s\n' "$out" | sed -n 's/^id	//p')
  WHERE_LAST_ROOT=$resolved
  content=$(printf '%s\n' "$ids" | LC_ALL=C sort | sha256_stream)
  total=$(awk 'NF' "$expected" | awk 'END { print NR + 0 }')
  read_count=$(printf '%s\n' "$ids" | awk 'NF' | awk 'END { print NR + 0 }')
  differing=$(printf '%s\n' "$ids" | awk -F'\t' 'NR == FNR { if (NF) e[$0] = 1; next } NF && !($0 in e) { n++ } END { print n + 0 }' "$expected" -)
  if [ "$read_count" -ne "$total" ]; then
    verdict="unreadable $read_count/$total"
    WHERE_OK=0
  elif [ "$differing" -eq 0 ]; then
    verdict=carries
  else
    verdict="differs $differing/$total"
    WHERE_OK=0
  fi
  [ "$dirty" = 0 ] && dirty=clean || dirty="dirty $dirty"
  printf 'where\t%s\t%s\t%s\t%s\t%s\t%s\t%s\t%s\n' \
    "$label" "$shown" "$resolved" "${head:0:12}" "$ref" "$dirty" "$content" "$verdict"
}

# --fleet: the home itself runs as the primary, and every second mate runs from
# its recorded code root. A remote mate has two more roots in play: the
# registry root, which fm-on.sh hands the remote job worker for every parent
# call, and the checkout fm-remote-entrypoint.sh resolves to on that host's
# PATH. Each one that is not the recorded root is a second runtime, so it gets
# its own row and a `disagree` line instead of being chosen silently.
where_fleet() {  # <home>
  local home reg line id host recorded registry_root entry
  home=$(resolved_existing_dir "$1") || die "fleet home is not a directory: $1"
  # shellcheck source=bin/fm-backend.sh
  . "$SCRIPT_DIR/fm-backend.sh"
  # shellcheck source=bin/fm-secondmate-registry-lib.sh
  . "$SCRIPT_DIR/fm-secondmate-registry-lib.sh"
  where_row primary "" "$home"
  reg=$home/data/secondmates.md
  [ -f "$reg" ] || return 0
  while IFS= read -r line <&3 || [ -n "$line" ]; do
    case "$line" in '- '*) ;; *) continue ;; esac
    if ! secondmate_registry_parse_line "$line"; then
      printf 'unparsed\t%s\n' "$line"
      WHERE_OK=0
      continue
    fi
    id=$SECONDMATE_REGISTRY_ID
    recorded=$(fm_meta_get "$home/state/$id.meta" code_root)
    if [ "$SECONDMATE_REGISTRY_REMOTE" -eq 1 ]; then
      host=$SECONDMATE_REGISTRY_HOST
      registry_root=$SECONDMATE_REGISTRY_ROOT
      [ -n "$recorded" ] || recorded=$registry_root
      where_row "$id" "$host" "$recorded"
      recorded=$WHERE_LAST_ROOT
      if [ "$registry_root" != "$recorded" ]; then
        where_row "$id@registry" "$host" "$registry_root"
        if [ "$WHERE_LAST_ROOT" != "$recorded" ]; then
          printf 'disagree\t%s\trecorded %s\tregistry %s\n' "$id" "$recorded" "$WHERE_LAST_ROOT"
          WHERE_OK=0
        fi
      fi
      entry=$(where_remote "$host" entry - </dev/null 2>/dev/null | sed -n 's/^entry	//p') || entry=
      if [ -n "$entry" ] && [ "$entry" != - ] && [ "$entry" != "$recorded" ]; then
        printf 'disagree\t%s\trecorded %s\tentrypoint %s\n' "$id" "$recorded" "$entry"
        WHERE_OK=0
        where_row "$id@entrypoint" "$host" "$entry"
      fi
    else
      [ -n "$recorded" ] || recorded=$SECONDMATE_REGISTRY_HOME
      where_row "$id" "" "$recorded"
    fi
  done 3< "$reg"
}

where_verb() {
  local manifest target
  manifest=$(manifest_file)
  [ -f "$STORE/expected.tsv" ] || die "the store has no expected.tsv; run replay to record what the set produces"
  command -v shasum >/dev/null 2>&1 || command -v sha256sum >/dev/null 2>&1 \
    || die 'neither shasum nor sha256sum is available to identify the checked content'
  [ -n "$WHERE_FLEET" ] || [ "${#WHERE_TARGETS[@]}" -gt 0 ] \
    || die 'where needs --fleet <home> or at least one target'
  WHERE_HOST=$(hostname -s 2>/dev/null || hostname)
  printf 'store\t%s\n' "$STORE"
  printf 'revision\t%s\tbase %s\tpatches %s\n' "$(store_revision "$manifest")" \
    "$(series_base "$manifest")" "$(patch_count "$manifest")"
  printf 'content\t%s\n' "$(expected_content)"
  [ -z "$WHERE_FLEET" ] || where_fleet "$WHERE_FLEET"
  for target in ${WHERE_TARGETS[@]+"${WHERE_TARGETS[@]}"}; do
    case "$target" in
      [A-Za-z0-9]*:/*) where_row "$target" "${target%%:*}" "${target#*:}" ;;
      *) where_row "$target" "" "$target" ;;
    esac
  done
  [ "$WHERE_OK" = 1 ]
}

# The scratch worktree is a sibling of the target so a conflicted run is easy to
# find and inspect. A replay's is never force-removed: a stale one means an
# earlier run stopped on a conflict, and that state is for a human to read
# first. `record` uses its own name so it never collides with that state.
scratch_path() {  # <target> [scratch|record]
  printf '%s.fm-patch-%s\n' "${1%/}" "${2:-scratch}"
}

# The base is the recorded, verified one by default, so the common operation -
# rebuilding the patched checkouts from a known-good set - cannot silently
# target a base the set was never verified against. `--base` is how an advance
# onto a newer upstream tip is attempted, and the replay then reports whatever
# conflicts that produces instead of moving anything.
replay_base() {  # <target> <manifest>
  local target=$1 manifest=$2 default recorded resolved
  if [ -n "$BASE_REV" ]; then
    resolved=$(git -C "$target" rev-parse --verify --quiet "$BASE_REV^{commit}") \
      || die "base does not exist in $target: $BASE_REV"
    printf '%s\n' "$resolved"
    return 0
  fi
  recorded=$(series_base "$manifest")
  if [ -n "$recorded" ] && [ "$recorded" != '-' ]; then
    resolved=$(git -C "$target" rev-parse --verify --quiet "$recorded^{commit}") \
      || die "the manifest records verified base $recorded but $target does not contain it; fetch it or pass --base"
    printf '%s\n' "$resolved"
    return 0
  fi
  default=$(default_branch "$target") || die "cannot determine the default branch of $target"
  resolved=$(git -C "$target" rev-parse --verify --quiet "origin/$default^{commit}") \
    || die "$target has no origin/$default to replay onto"
  printf '%s\n' "$resolved"
}

replay_verb() {
  local target=$1 manifest base scratch tip prev current default
  [ -n "$target" ] || die 'replay needs a target checkout'
  [ -d "$target" ] || die "target is not a directory: $target"
  git -C "$target" rev-parse --is-inside-work-tree >/dev/null 2>&1 \
    || die "target is not a git checkout: $target"
  manifest=$(manifest_file)

  # Refuse before doing anything: an unclean target is never worked around.
  if [ -n "$(dirty_status "$target")" ]; then
    die "target has unlanded changes, refusing to replay over them: $target"
  fi
  # A patched checkout is detached or on its own branch by construction. Moving a
  # checkout that sits ON the default branch would detach it there, which is the
  # diverged, un-fast-forwardable state this tool exists to prevent - the very
  # thing the fast-forward-only update path refuses.
  current=$(git -C "$target" symbolic-ref --quiet --short HEAD 2>/dev/null || true)
  if [ -n "$current" ]; then
    default=$(default_branch "$target" 2>/dev/null || true)
    if [ -n "$default" ] && [ "$current" = "$default" ]; then
      die "refusing to replay onto $target: it is on its default branch $current, and a patched checkout must be detached or on its own branch so $default stays an ancestor of origin"
    fi
  fi
  scratch=$(scratch_path "$target")
  if [ -e "$scratch" ]; then
    die "scratch worktree already exists (a previous run stopped here for inspection): $scratch"
  fi

  base=$(replay_base "$target" "$manifest")
  printf 'replay\t%s\ton %s\n' "$target" "$base"

  git -C "$target" worktree add --detach "$scratch" "$base" >/dev/null 2>&1 \
    || die "could not create the scratch worktree at $scratch"

  if ! apply_series "$scratch" "$base" "$manifest"; then
    printf 'error: patch %s (%s) did not apply to %s; the target is untouched\n' "$APPLY_CONFLICT_ID" "$APPLY_CONFLICT_SLUG" "$base" >&2
    printf 'error: the scratch worktree is kept as it stopped: %s\n' "$scratch" >&2
    printf 'error: resolve and commit there, then regenerate the patch with: %s --store %s --base %s record %s --id %s --slug %s --repo %s --commit HEAD\n' \
      "$0" "$STORE" "$base" "$target" "$APPLY_CONFLICT_ID" "$APPLY_CONFLICT_SLUG" "$scratch" >&2
    printf 'error: remove the scratch only once record has accepted the regenerated patch; until then it holds the only copy of the resolution\n' >&2
    exit 1
  fi
  tip=$APPLY_TIP
  prev=$(git -C "$target" rev-parse HEAD)

  # The whole series is on disk and verified only now, so this is the first
  # moment anything may move. Record what the set produces first: `check` reads
  # this, so it is the file that lets any host prove it carries the same content
  # without a tree transfer.
  write_expected "$scratch" "$base" "$tip"
  printf 'expected\t%s\n' "$STORE/expected.tsv"

  # Label the tip the target is leaving before it moves, so the move never
  # strands it, and only then repoint the target.
  git -C "$target" update-ref "refs/farm-patches/history/$prev" "$prev"
  git -C "$target" update-ref refs/farm-patches/previous "$prev"
  git -C "$target" update-ref refs/farm-patches/current "$tip"
  git -C "$target" worktree remove "$scratch" >/dev/null 2>&1 \
    || die "the replay succeeded but the scratch worktree could not be removed: $scratch"
  git -C "$target" checkout --detach "$tip" >/dev/null 2>&1 \
    || die "the replay succeeded but the target could not be moved to $tip"
  printf 'replayed\t%s\t%s\t%s\n' "$target" "$prev" "$tip"
}

# The one place the series is applied, shared by `replay` and `record` so both
# refuse on exactly the same condition. It commits one commit per patch in
# <scratch> (already checked out at <base>), prints one `applied` line per patch,
# and sets APPLY_TIP on success. On the first patch that does not apply it prints
# the `conflict` line, passes the rejecting patch's own diagnostics to stderr,
# sets APPLY_CONFLICT_ID, APPLY_CONFLICT_SLUG and APPLY_CONFLICT_FILE, and
# returns 1 with the scratch left exactly as it stopped, for inspection.
apply_series() {  # <scratch> <base> <manifest>
  local scratch=$1 base=$2 manifest=$3 count i id slug file origin subject
  count=$(patch_count "$manifest")
  i=0
  while [ "$i" -lt "$count" ]; do
    i=$((i + 1))
    id=$(patch_field "$manifest" "$i" 2)
    slug=$(patch_field "$manifest" "$i" 3)
    file=$(patch_field "$manifest" "$i" 4)
    origin=$(patch_field "$manifest" "$i" 5)
    subject=$(patch_field "$manifest" "$i" 7)
    [ -f "$STORE/$file" ] || die "patch file missing from the store: $STORE/$file"
    if ! git -C "$scratch" apply "$STORE/$file" 2> "$scratch/.fm-patch-error"; then
      printf 'conflict\t%s\t%s\t%s\n' "$id" "$slug" "$file"
      sed 's/^/  /' "$scratch/.fm-patch-error" >&2
      rm -f "$scratch/.fm-patch-error"
      APPLY_CONFLICT_ID=$id
      APPLY_CONFLICT_SLUG=$slug
      APPLY_CONFLICT_FILE=$file
      return 1
    fi
    rm -f "$scratch/.fm-patch-error"
    git -C "$scratch" add -A -- .
    git -C "$scratch" commit -q -m "$subject" -m "farm-patch $id ($slug) from $origin" \
      || die "could not commit patch $id in the scratch worktree"
    printf 'applied\t%s\t%s\t%s\n' "$id" "$slug" "$file"
  done
  APPLY_TIP=$(git -C "$scratch" rev-parse HEAD)
  return 0
}

# expected.tsv is what the set produces over the whole base..tip range, written
# from the scratch the series was just applied in. Both writers call this, so the
# format has one owner.
write_expected() {  # <scratch> <base> <tip>
  git -C "$1" -c core.abbrev=40 diff --raw --no-renames "$2" "$3" \
    | awk -F'\t' '{ split($1, m, " "); if (m[2] == "000000") printf "000000\t-\t%s\n", $2; else printf "%s\t%s\t%s\n", m[2], m[4], $2 }' \
    | LC_ALL=C sort -k3 > "$STORE/expected.tsv"
}

# Patch ids are four digits so they sort as written and so a file name carries
# its application position. The next free one is one past the highest recorded.
next_patch_id() {  # <manifest>
  patch_records "$1" | awk -F'\t' '{ n = $2 + 0 } END { printf "%04d\n", (n > max ? n : max) + 1 }'
}

patch_index_of() {  # <manifest> <id> -> prints the 1-based record position, or nothing
  patch_records "$1" | awk -F'\t' -v id="$2" '$2 == id { print NR; exit }'
}

# Rewrites the manifest with the series record and one patch record moved, and
# nothing else touched: every comment line and every untouched record keeps its
# place, and a new patch record is inserted where its id belongs, so application
# order and id order stay the same thing.
manifest_edit() {  # <src> <dest> <series-line> <id> <replace 0|1> <patch-line>
  awk -F'\t' -v series="$3" -v wid="$4" -v replace="$5" -v pline="$6" '
    BEGIN { placed = 0; wrote_series = 0 }
    /^series\t/ { if (!wrote_series) { print series; wrote_series = 1 } else { print }; next }
    /^patch\t/ {
      if (replace == 1 && $2 == wid) { if (!placed) { print pline; placed = 1 }; next }
      if (replace == 0 && !placed && ($2 + 0) > (wid + 0)) { print pline; placed = 1 }
      print
      next
    }
    { print }
    END {
      if (!placed) print pline
      if (!wrote_series) print series
    }
  ' "$1" > "$2"
}

# The write side of the set. A patch file, its manifest record, and the series
# base move as one act, and the whole series has to apply through the recorded
# patch before any of it stays: a store that cannot use a patch is worse than a
# refused record, because every later replay fails on it.
record_verb() {
  local target=$1 manifest base scratch slug id file old_file replace repo commit from
  local patch_src series_line patch_line i had_new=0 kept_old=0
  local conflict_ok=0
  [ -n "$target" ] || die 'record needs a target checkout'
  [ -d "$target" ] || die "target is not a directory: $target"
  git -C "$target" rev-parse --is-inside-work-tree >/dev/null 2>&1 \
    || die "target is not a git checkout: $target"
  manifest=$(manifest_file)

  [ -n "$SLUG" ] || die 'record needs --slug to name the patch'
  case "$SLUG" in
    *[!a-z0-9-]*) die "slug must use only lowercase letters, digits and dashes: $SLUG" ;;
  esac
  [ -n "$RECORD_DIFF" ] && [ -n "$RECORD_COMMIT" ] \
    && die 'record takes a diff or a commit, not both'
  [ -z "$RECORD_DIFF" ] && [ -z "$RECORD_COMMIT" ] \
    && die 'record needs --diff <file|-> or --commit <rev>'

  # record builds in its own scratch, beside the one a conflicted replay keeps,
  # so a resolution committed in the replay's scratch can be recorded straight
  # from there (--repo <that scratch> --commit HEAD) without touching it. A
  # stale record scratch means an earlier record was interrupted: refuse before
  # writing anything rather than clobbering it.
  scratch=$(scratch_path "$target" record)
  [ -e "$scratch" ] \
    && die "record scratch worktree already exists (an earlier record was interrupted): $scratch"

  RECORD_TMP=$(mktemp -d "${TMPDIR:-/tmp}/fm-farm-patch-record.XXXXXX") \
    || die 'could not create a working directory'
  trap 'rm -rf "${RECORD_TMP:-}"' EXIT

  if [ -n "$RECORD_ID" ]; then
    case "$RECORD_ID" in
      *[!0-9]*|'') die "--id must be a four-digit number: $RECORD_ID" ;;
    esac
    [ "${#RECORD_ID}" -eq 4 ] || die "--id must be a four-digit number: $RECORD_ID"
    id=$RECORD_ID
  else
    id=$(next_patch_id "$manifest")
  fi
  file="$id-$SLUG.patch"
  i=$(patch_index_of "$manifest" "$id")
  if [ -n "$i" ]; then
    # Regenerating a patch that is already in the set keeps that record's own
    # description unless this run names a new one. This is resolved before the
    # source is read so no source-shaped default (a working copy's path, a
    # throwaway commit subject) can replace durable provenance a record already
    # carries.
    replace=1
    old_file=$(patch_field "$manifest" "$i" 4)
    [ -n "$RECORD_ORIGIN" ] || RECORD_ORIGIN=$(patch_field "$manifest" "$i" 5)
    [ -n "$RECORD_PURPOSE" ] || RECORD_PURPOSE=$(patch_field "$manifest" "$i" 6)
    [ -n "$RECORD_SUBJECT" ] || RECORD_SUBJECT=$(patch_field "$manifest" "$i" 7)
  else
    replace=0
    [ -e "$STORE/$file" ] \
      && die "the store already holds $file with no manifest record; refusing to overwrite it"
  fi

  # Exactly one source, so the recorded bytes are the ones named on the command
  # line rather than whatever a later step happens to produce.
  if [ -n "$RECORD_COMMIT" ]; then
    repo=${RECORD_REPO:-$target}
    [ -d "$repo" ] || die "--repo is not a directory: $repo"
    commit=$(git -C "$repo" rev-parse --verify --quiet "$RECORD_COMMIT^{commit}") \
      || die "--commit does not exist in $repo: $RECORD_COMMIT"
    if [ -n "$RECORD_FROM" ]; then
      from=$(git -C "$repo" rev-parse --verify --quiet "$RECORD_FROM^{commit}") \
        || die "--from does not exist in $repo: $RECORD_FROM"
    else
      from=$(git -C "$repo" rev-parse --verify --quiet "$commit^") \
        || die "--commit $commit has no parent to diff against; pass --from"
    fi
    patch_src=$RECORD_TMP/commit.patch
    git -C "$repo" diff --no-color --no-ext-diff --no-renames --binary "$from" "$commit" > "$patch_src" \
      || die "could not diff $from..$commit in $repo"
    [ -s "$patch_src" ] || die "$from..$commit in $repo is an empty diff; nothing to record"
    [ -n "$RECORD_SUBJECT" ] || RECORD_SUBJECT=$(git -C "$repo" log -1 --format=%s "$commit")
    [ -n "$RECORD_ORIGIN" ] || RECORD_ORIGIN="$repo ${from:0:7}..${commit:0:7}"
  else
    if [ "$RECORD_DIFF" = "-" ]; then
      patch_src=$RECORD_TMP/stdin.patch
      cat > "$patch_src"
    else
      [ -f "$RECORD_DIFF" ] || die "--diff is not a file: $RECORD_DIFF"
      patch_src=$RECORD_DIFF
    fi
    [ -s "$patch_src" ] || die 'the diff to record is empty'
  fi

  [ -n "$RECORD_ORIGIN" ] || RECORD_ORIGIN="recorded $(date +%F) by fm-farm-patch.sh record"
  [ -n "$RECORD_PURPOSE" ] || RECORD_PURPOSE=$SLUG
  [ -n "$RECORD_SUBJECT" ] || RECORD_SUBJECT=$SLUG

  # The base is the one the whole set is verified on, and the series record is
  # its single owner: recording what was just verified is what keeps that record
  # true rather than aspirational.
  base=$(replay_base "$target" "$manifest")
  series_line=$(printf 'series\t%s\t%s\t%s' "$base" "$(date +%F)" \
    "${RECORD_NOTE:-recorded by fm-farm-patch.sh record}")
  patch_line=$(printf 'patch\t%s\t%s\t%s\t%s\t%s\t%s' \
    "$id" "$SLUG" "$file" "$RECORD_ORIGIN" "$RECORD_PURPOSE" "$RECORD_SUBJECT")

  cp "$STORE/manifest" "$RECORD_TMP/manifest.old"
  if [ -e "$STORE/$file" ]; then cp "$STORE/$file" "$RECORD_TMP/patch.old"; had_new=1; fi
  if [ "$replace" = 1 ] && [ "$old_file" != "$file" ]; then
    cp "$STORE/$old_file" "$RECORD_TMP/renamed.old"
    kept_old=1
  fi

  cp "$patch_src" "$STORE/$file"
  manifest_edit "$STORE/manifest" "$RECORD_TMP/manifest.new" "$series_line" "$id" "$replace" "$patch_line"
  cp "$RECORD_TMP/manifest.new" "$STORE/manifest"
  [ "$kept_old" = 1 ] && rm -f "$STORE/$old_file"

  git -C "$target" worktree add --detach "$scratch" "$base" >/dev/null 2>&1 \
    || die "could not create the scratch worktree at $scratch"

  if ! apply_series "$scratch" "$base" "$STORE/manifest"; then
    # A conflict past the patch just recorded means the store is mid-repair and
    # the record is worth keeping, because the next patch is the one still to
    # fix. A conflict at or before it means this record cannot be used at all, so
    # nothing of it stays.
    if [ "$APPLY_CONFLICT_ID" \> "$id" ]; then
      conflict_ok=1
    else
      conflict_ok=0
    fi
  fi

  if [ -n "${APPLY_CONFLICT_ID:-}" ] && [ "$conflict_ok" = 0 ]; then
    cp "$RECORD_TMP/manifest.old" "$STORE/manifest"
    if [ "$had_new" = 1 ]; then cp "$RECORD_TMP/patch.old" "$STORE/$file"; else rm -f "$STORE/$file"; fi
    if [ "$kept_old" = 1 ]; then cp "$RECORD_TMP/renamed.old" "$STORE/$old_file"; fi
    git -C "$target" worktree remove --force "$scratch" >/dev/null 2>&1 || true
    printf 'error: patch %s (%s) does not apply to %s even with %s recorded; the store is unchanged\n' \
      "$APPLY_CONFLICT_ID" "$APPLY_CONFLICT_SLUG" "$base" "$id" >&2
    exit 1
  fi

  if [ "$conflict_ok" = 1 ]; then
    git -C "$target" worktree remove --force "$scratch" >/dev/null 2>&1 \
      || die "the record succeeded but the scratch worktree could not be removed: $scratch"
    printf 'recorded\t%s\t%s\t%s\n' "$id" "$SLUG" "$file"
    printf 'series\t%s\t%s\t%s\n' "$base" "$(date +%F)" "${RECORD_NOTE:-recorded by fm-farm-patch.sh record}"
    printf 'incomplete\t%s\t%s\t%s\n' "$APPLY_CONFLICT_ID" "$APPLY_CONFLICT_SLUG" "$APPLY_CONFLICT_FILE"
    printf 'warning: patch %s still stops the series, so expected.tsv describes the set as it was before %s\n' \
      "$APPLY_CONFLICT_ID" "$id" >&2
    exit 0
  fi

  write_expected "$scratch" "$base" "$APPLY_TIP"
  git -C "$target" worktree remove "$scratch" >/dev/null 2>&1 \
    || die "the record succeeded but the scratch worktree could not be removed: $scratch"
  printf 'recorded\t%s\t%s\t%s\n' "$id" "$SLUG" "$file"
  printf 'series\t%s\t%s\t%s\n' "$base" "$(date +%F)" "${RECORD_NOTE:-recorded by fm-farm-patch.sh record}"
  printf 'expected\t%s\n' "$STORE/expected.tsv"
}

resolve_store() {
  local resolved
  resolved=$(cd "$STORE" 2>/dev/null && pwd -P) \
    || die "store is not a directory: $STORE"
  STORE=$resolved
}

resolve_target() {
  local resolved
  [ -n "$TARGET" ] || return 0
  resolved=$(resolved_existing_dir "$TARGET") || resolved=$(resolve_path "$TARGET")
  TARGET=$resolved
}

main() {
  parse_args "$@"
  resolve_store
  resolve_target
  case "$VERB" in
    list) list_verb ;;
    check) [ -n "$TARGET" ] || die 'check needs a target checkout'; check_verb "$TARGET" ;;
    record) [ -n "$TARGET" ] || die 'record needs a target checkout'; record_verb "$TARGET" ;;
    replay) [ -n "$TARGET" ] || die 'replay needs a target checkout'; replay_verb "$TARGET" ;;
    where) where_verb ;;
    *) usage >&2; exit 1 ;;
  esac
}

main "$@"
