#!/usr/bin/env bash
# fm-farm-patch.sh - keep one explicit, enumerable patch set alive on top of a
# fast-forward-only firstmate checkout.
#
# Why this exists. bin/fm-ff-lib.sh advances a home only by a clean
# fast-forward, so any local commit on a default branch makes that checkout
# permanently "skipped: diverged" for /updatefirstmate - exactly the trap a fork
# with its own fixes falls into. This tool keeps those fixes as a NAMED PATCH SET
# that lives off the default branch, so the default branch stays an ancestor of
# origin and still fast-forwards, while a separate checkout carries the patched
# content and is rebuilt by a scripted, non-destructive replay.
#
# The store. A directory (default: <repo-root>/farm-patches) holding:
#   manifest                  the ordered list: one `series` record
#                             (`series` <TAB> verified base <TAB> date <TAB> note)
#                             then one `patch` record per patch
#                             (`patch` <TAB> id <TAB> slug <TAB> file <TAB> origin
#                             <TAB> purpose <TAB> commit subject)
#   <NNNN>-<slug>.patch       one unified diff per patch, applied in id order
#   expected.tsv              the content the series produces, one
#                             `<mode> <TAB> <blob> <TAB> <path>` line per file the
#                             set touches. Generated by `replay`, and by `record`
#                             once the whole set applies - never by hand - and
#                             committed with the set so `check` can be run
#                             read-only on any host. Commit it after a green
#                             replay, or `check` compares against a stale set.
#   ROLLOUT.md                optional operator notes for the owning fleet
# The manifest is the single owner of the set. Adding, removing, or reordering a
# patch is an edit to that file and is therefore an explicit, recorded act - and
# `record` is the only writer of it, so that act is scripted rather than manual.
#
# Verbs:
#   list   [--store <dir>]
#       Print the named patch set in application order, with its `revision`
#       (the set's own identity: the verified base plus every patch file's
#       bytes, in order) and its `content` (the digest `check` prints as its
#       `set` line for a checkout that carries the set exactly).
#   check  [--store <dir>] <target>
#       Compare one checkout against the content the set produces, file by file.
#       Three hosts that print the same `set` line carry the same patch content.
#       Read-only against the target.
#   record [--store <dir>] [--base <rev>] <target> --slug <slug>
#          [--id <NNNN>] [--repo <dir>] [--from <rev>] [--commit <rev>]
#          [--diff <file>|'-'] [--origin <text>] [--purpose <text>]
#          [--subject <text>] [--note <text>]
#       Write one patch file, update its manifest record, and record the base
#       the whole set was verified against. This is the write side of the set:
#       regenerating a patch after a conflict, and adding the patch that has no
#       verb, both go through here instead of through a hand-edited diff.
#       The patch content comes from exactly one source: `--diff` reads a
#       unified diff (or stdin for '-'), and `--commit` takes the diff that
#       commit introduces in `--repo` (`--from` names its parent explicitly,
#       and defaults to the commit's own parent).
#       An `--id` that already exists replaces that patch in place; otherwise
#       the new record is inserted in id order and the id defaults to the next
#       free number. The whole series is then applied on the base in a scratch
#       worktree: a conflict at or before the recorded patch refuses and leaves
#       the store untouched, a conflict after it keeps the record and reports
#       the set as incomplete, and a clean run regenerates expected.tsv.
#   replay [--store <dir>] [--base <rev>] <target>
#       Rebuild the patched lineage and point <target> at it. The base defaults
#       to the commit the manifest records as verified, and `--base` is how an
#       advance onto a newer upstream tip is attempted. Nothing moves until the
#       whole series applies, so a conflict cannot leave the target half-patched.
#       A conflict leaves the scratch worktree exactly as it stopped. Resolve
#       and commit there, regenerate the patch with `record <target> --id <id>
#       --repo <scratch> --commit HEAD` (record builds in its own scratch, so it
#       never collides with this one), and remove the scratch only once record
#       has accepted the patch: until then it holds the only copy of that work.
#   where  [--store <dir>] [--fleet <home>] [<target>|<host>:<root>]...
#       Name, for each code root, the checkout it is (root, HEAD, branch or
#       detached, uncommitted path count) and whether it carries this store's
#       content: one `where` row per root, ending in `carries`,
#       `differs <k>/<n>`, `unreadable`, `missing`, or `unreachable`. A
#       `<host>:<root>` target is read over non-interactive ssh with the same
#       file identity `check` uses, so the remote host needs git but neither
#       this tool nor the store. `--fleet <home>` expands to the roots that
#       home's fleet runs from: the home itself as `primary` (a primary runs its
#       own home's scripts), and for every second mate in
#       <home>/data/secondmates.md the code root recorded as code_root= in
#       <home>/state/<id>.meta, falling back to the registry root. A remote mate
#       has two more roots in play: the registry root, which fm-on.sh hands the
#       remote job worker for every parent call, and the checkout
#       fm-remote-entrypoint.sh resolves to on that host's non-interactive
#       PATH. Each that names another checkout gets its own `<id>@registry` or
#       `<id>@entrypoint` row and a `disagree` line, so no root is ever selected
#       silently. Read-only everywhere. Exits 0 only when every row carries the
#       set and nothing disagrees. FM_FARM_PATCH_SSH replaces the ssh client.
#
# Safety contract, enforced by refusal rather than by repair:
#   - fast-forward is not possible here by construction (a patch lineage is not a
#     descendant of upstream), so the target is moved with `checkout --detach`
#     onto a commit this run built, never with `reset --hard` and never with a
#     merge commit.
#   - a dirty target, a target holding a stale scratch worktree, or a missing
#     base is refused before any work starts.
#   - a conflict stops at the first failing patch, prints it, leaves the scratch
#     worktree in place for inspection, and exits non-zero. Nothing is forced,
#     stashed, 3-way merged, or discarded, and a later replay or record refuses
#     while that scratch exists rather than replacing it.
#   - the target's previous tip is recorded under refs/farm-patches/previous
#     before the target moves, so a replay never makes an earlier tip
#     unreachable.
#   - a scratch worktree is a linked worktree of the target's own repo, so this
#     tool never fetches, never touches another checkout, and never writes
#     outside the target's parent directory.
#   - `record` is the only verb that writes the store, and it writes it as one
#     act: the patch file, the manifest record, and the series base move
#     together, and a set that does not apply through the recorded patch puts
#     every one of them back. A record never leaves a patch the set cannot use.
#
# Usage: fm-farm-patch.sh [--store <dir>] [--base <rev>] <verb> [<target>...]
set -eu

