FM_ROOT="${FM_ROOT_OVERRIDE:-$(cd "$SCRIPT_DIR/.." && pwd)}"
# shellcheck source=bin/fm-ff-lib.sh
. "$SCRIPT_DIR/fm-ff-lib.sh"

STORE="${FM_FARM_PATCH_STORE:-$FM_ROOT/farm-patches}"
BASE_REV=""
VERB=""
TARGET=""
